export const MOBILE_UI_TRANSLATIONS: Readonly<
  Record<GlossaryLanguage, Readonly<Record<MobileUiKey, string>>>
> = (() => {
  const built = {} as Record<GlossaryLanguage, Readonly<Record<MobileUiKey, string>>>;
  for (const langInfo of GLOSSARY_LANGUAGES) {
    const code = langInfo.code;
    if (code === 'tr') {
      built.tr = TR_UI;
    } else if (code === 'en') {
      built.en = EN_UI;
    } else {
      built[code] = Object.freeze({ ...EN_UI, ...EXTRA_LOCALES[code] });
    }
  }
  return Object.freeze(built);
})();

export function translateMobileUi(
  lang: GlossaryLanguage,
  key: MobileUiKey,
  vars?: Record<string, string | number>
): string {
  const safeLang = sanitizeGlossaryLanguage(lang, 'tr');
  const dict = Object.hasOwn(MOBILE_UI_TRANSLATIONS, safeLang)
    ? MOBILE_UI_TRANSLATIONS[safeLang]
    : EN_UI;
  let template = Object.hasOwn(dict, key) ? dict[key] : EN_UI[key];
  if (!vars) return template;
  for (const [k, v] of Object.entries(vars)) {
    template = template.replaceAll(`{${k}}`, String(v));
  }
  return template;
}
